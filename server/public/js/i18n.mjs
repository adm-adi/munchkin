export function avatarEmoji(avatarId, gender) {
    const idx = ((Math.trunc(Number(avatarId) || 0) % AVATARS.length) + AVATARS.length) % AVATARS.length;
    const slot = AVATARS[idx];
    return gender === 'F' ? slot.f : slot.m;
}

